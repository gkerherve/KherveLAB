/* KherveLAB web calendar: the same slots, cards, colours and gestures as the
   desktop app. Slots come from /api/calendar (generated by the app's own
   rules), and a booking is previewed with /api/quote before it is sent, so
   the web can only offer and book what the instrument settings allow.

   Times are lab wall-clock strings ("YYYY-MM-DDTHH:MM"). Date arithmetic is
   done on UTC dates so the browser's own time zone never shifts a slot. */
(function () {
  "use strict";

  var PPM = 0.75;            // pixels per minute (45 px per hour)
  var HOLD_MS = 600;         // press and hold this long to book one slot
  var DRAG_PX = 6;           // movement that turns a press into a drag
  var DAY_NAMES = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"];
  var MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

  function pad(n) { return (n < 10 ? "0" : "") + n; }
  function dayKey(d) { return d.getUTCFullYear() + "-" + pad(d.getUTCMonth() + 1) + "-" + pad(d.getUTCDate()); }
  function parseDay(s) { var p = s.split("-"); return new Date(Date.UTC(+p[0], +p[1] - 1, +p[2])); }
  function addDays(d, n) { return new Date(d.getTime() + n * 86400000); }
  function mondayOf(d) { var w = (d.getUTCDay() + 6) % 7; return addDays(d, -w); }
  function minutesFrom(dayStart, stamp) {
    // minutes from 00:00 of dayStart (a UTC date) to a wall-clock stamp
    var day = parseDay(stamp.slice(0, 10));
    var hm = stamp.slice(11, 16).split(":");
    return (day - dayStart) / 60000 + (+hm[0]) * 60 + (+hm[1]);
  }
  function hhmm(stamp) { return stamp.slice(11, 16); }
  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text != null) e.textContent = text;
    return e;
  }
  function money(cur, x) { return cur + Number(x).toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 }); }

  function KherveCal(root, opts) {
    this.root = root;
    this.o = opts;
    this.mode = window.matchMedia("(max-width: 760px)").matches ? "day" : "week";
    var start = opts.date ? parseDay(opts.date) : parseDay(opts.today);
    this.anchor = start;
    this.data = null;
    this.drag = null;
    this.build();
    this.load();
  }

  KherveCal.prototype.range = function () {
    var first = this.mode === "week" ? mondayOf(this.anchor) : this.anchor;
    var days = this.mode === "week" ? 7 : 1;
    var list = [];
    for (var i = 0; i < days; i++) list.push(addDays(first, i));
    return list;
  };

  KherveCal.prototype.build = function () {
    var self = this;
    this.root.innerHTML = "";
    var bar = el("div", "kc-toolbar");
    var nav = el("div", "kc-nav");
    [["◀", -1], ["Today", 0], ["▶", 1]].forEach(function (b) {
      var btn = el("button", "kc-btn", b[0]);
      btn.type = "button";
      btn.addEventListener("click", function () { self.step(b[1]); });
      nav.appendChild(btn);
    });
    this.title = el("div", "kc-title");
    var views = el("div", "kc-views");
    this.viewButtons = {};
    [["day", "Day"], ["week", "Week"]].forEach(function (v) {
      var btn = el("button", "kc-btn", v[1]);
      btn.type = "button";
      btn.addEventListener("click", function () { self.mode = v[0]; self.load(); });
      self.viewButtons[v[0]] = btn;
      views.appendChild(btn);
    });
    bar.appendChild(nav); bar.appendChild(this.title); bar.appendChild(views);
    this.legend = el("div", "kc-legend");
    this.head = el("div", "kc-head");
    this.scroll = el("div", "kc-scroll");
    this.body = el("div", "kc-body");
    this.scroll.appendChild(this.body);
    this.toast = el("div", "kc-toast");
    this.root.appendChild(bar);
    this.root.appendChild(this.legend);
    this.root.appendChild(this.head);
    this.root.appendChild(this.scroll);
    this.root.appendChild(this.toast);
    this.scrolled = false;
  };

  KherveCal.prototype.step = function (n) {
    if (n === 0) this.anchor = parseDay(this.o.today);
    else this.anchor = addDays(this.anchor, n * (this.mode === "week" ? 7 : 1));
    this.load();
  };

  KherveCal.prototype.load = function () {
    var self = this;
    var days = this.range();
    var start = dayKey(days[0]) + "T00:00";
    var end = dayKey(addDays(days[days.length - 1], 1)) + "T00:00";
    var url = this.o.calendarUrl + "?instrument=" + this.o.instrument +
      "&start=" + encodeURIComponent(start) + "&end=" + encodeURIComponent(end);
    fetch(url, { credentials: "same-origin" })
      .then(function (r) { return r.json(); })
      .then(function (data) { self.data = data; self.days = days; self.render(); });
  };

  KherveCal.prototype.render = function () {
    var self = this, d = this.data, days = this.days, pal = d.palette;
    Object.keys(this.viewButtons).forEach(function (k) {
      self.viewButtons[k].classList.toggle("on", k === self.mode);
    });
    var a = days[0], b = days[days.length - 1];
    this.title.textContent = this.mode === "day"
      ? DAY_NAMES[(a.getUTCDay() + 6) % 7] + " " + a.getUTCDate() + " " + MONTHS[a.getUTCMonth()] + " " + a.getUTCFullYear()
      : a.getUTCDate() + " " + MONTHS[a.getUTCMonth()] + " – " + b.getUTCDate() + " " + MONTHS[b.getUTCMonth()] + " " + b.getUTCFullYear();

    // legend
    this.legend.innerHTML = "";
    [["free", "free"], ["closed", "closed"], ["booked", "booked"], ["problem", "problem"], ["down", "out of order"]]
      .forEach(function (x) {
        var chip = el("span", "kc-chip");
        chip.style.background = pal[x[0]];
        self.legend.appendChild(chip);
        self.legend.appendChild(el("span", "kc-chip-label", x[1]));
      });

    // header
    this.head.innerHTML = "";
    this.head.appendChild(el("div", "kc-gutter-head"));
    days.forEach(function (day) {
      var h = el("div", "kc-day-head");
      if (dayKey(day) === self.o.today) h.classList.add("today");
      h.appendChild(el("b", null, DAY_NAMES[(day.getUTCDay() + 6) % 7]));
      h.appendChild(el("span", null, " " + day.getUTCDate() + " " + MONTHS[day.getUTCMonth()]));
      self.head.appendChild(h);
    });

    // body
    this.body.innerHTML = "";
    var gutter = el("div", "kc-gutter");
    gutter.style.height = (1440 * PPM) + "px";
    for (var hr = 1; hr < 24; hr++) {
      var t = el("div", "kc-hour", pad(hr) + ":00");
      t.style.top = (hr * 60 * PPM - 7) + "px";
      gutter.appendChild(t);
    }
    this.body.appendChild(gutter);
    this.slotEls = [];
    this.cols = [];
    days.forEach(function (day, ci) {
      var col = el("div", "kc-col");
      col.style.height = (1440 * PPM) + "px";
      col.style.background = pal.closed;
      col.dataset.col = ci;
      if (dayKey(day) === self.o.today) col.classList.add("today");
      self.cols.push(col);
      d.slots.forEach(function (s, si) {
        var m0 = Math.max(0, minutesFrom(day, s.start)), m1 = Math.min(1440, minutesFrom(day, s.end));
        if (m1 <= m0) return;
        var card = el("div", "kc-card kc-" + s.state);
        card.style.top = (m0 * PPM + 2) + "px";
        card.style.height = Math.max(6, (m1 - m0) * PPM - 5) + "px";
        card.style.setProperty("--c", pal[s.state === "free" ? "free" : s.state]);
        card.dataset.slot = si;
        if (minutesFrom(day, s.start) >= 0 && (m1 - m0) * PPM > 16) {
          var span = hhmm(s.start) + "–" + hhmm(s.end);
          var label = (s.label && s.label !== "Daytime" ? s.label + " " : "") + span +
            (s.state === "down" ? " · out of order" : s.state === "problem" ? " · problem" : "");
          card.appendChild(el("div", "kc-card-label", label));
        }
        col.appendChild(card);
        (self.slotEls[si] = self.slotEls[si] || []).push(card);
      });
      d.bookings.forEach(function (bk) {
        var m0 = Math.max(0, minutesFrom(day, bk.start)), m1 = Math.min(1440, minutesFrom(day, bk.end));
        if (m1 <= m0) return;
        var card = el("div", "kc-card kc-booked" + (bk.status === "pending" ? " kc-pending" : "") +
          (bk.mine ? " kc-mine" : "") + (bk.issue ? " kc-issue-" + bk.issue : ""));
        card.style.top = (m0 * PPM + 2) + "px";
        card.style.height = Math.max(6, (m1 - m0) * PPM - 5) + "px";
        card.style.setProperty("--c", pal.booked);
        if (bk.issue) card.style.setProperty("--o", pal[bk.issue]);
        var long = minutesFrom(parseDay(bk.start.slice(0, 10)), bk.end) >= 1440;
        var when = long ? bk.start.slice(5, 10) + " " + hhmm(bk.start) + "–" + bk.end.slice(5, 10) + " " + hhmm(bk.end)
          : hhmm(bk.start) + "–" + hhmm(bk.end);
        card.appendChild(el("div", "kc-card-title", when + " " + bk.who));
        var sub = (bk.purpose || "") + (bk.status === "pending" ? " (pending)" : "");
        if (sub) card.appendChild(el("div", "kc-card-sub", sub));
        card.addEventListener("click", function (ev) { ev.stopPropagation(); self.showBooking(bk); });
        col.appendChild(card);
      });
      if (dayKey(day) === self.o.today) {
        var now = el("div", "kc-now");
        now.style.top = (self.o.nowMinutes * PPM) + "px";
        col.appendChild(now);
      }
      self.wire(col, ci);
      self.body.appendChild(col);
    });
    this.head.style.gridTemplateColumns = this.body.style.gridTemplateColumns =
      "52px repeat(" + days.length + ", minmax(0, 1fr))";
    if (!this.scrolled) { this.scroll.scrollTop = 7 * 60 * PPM; this.scrolled = true; }
  };

  // -- selecting slots: drag across them, or press and hold one ------------------------
  KherveCal.prototype.slotAt = function (ci, y) {
    var day = this.days[ci], minute = y / PPM, slots = this.data.slots;
    for (var i = 0; i < slots.length; i++) {
      if (minutesFrom(day, slots[i].start) <= minute && minute < minutesFrom(day, slots[i].end)) return i;
    }
    return -1;
  };

  KherveCal.prototype.highlight = function (i, j) {
    (this.slotEls || []).forEach(function (els) { (els || []).forEach(function (e) { e.classList.remove("kc-sel"); }); });
    if (i < 0 || j < 0) return;
    for (var k = Math.min(i, j); k <= Math.max(i, j); k++) {
      (this.slotEls[k] || []).forEach(function (e) { e.classList.add("kc-sel"); });
    }
  };

  KherveCal.prototype.wire = function (col, ci) {
    var self = this;
    col.addEventListener("pointerdown", function (ev) {
      if (ev.button !== 0 || ev.target.closest(".kc-booked")) return;
      var y = ev.clientY - col.getBoundingClientRect().top;
      var i = self.slotAt(ci, y);
      if (i < 0) return;
      col.setPointerCapture(ev.pointerId);
      var drag = { first: i, last: i, x: ev.clientX, y: ev.clientY, armed: false };
      self.drag = drag;
      drag.timer = setTimeout(function () {
        if (self.drag === drag) { drag.armed = true; self.highlight(drag.first, drag.last); }
      }, HOLD_MS);
    });
    col.addEventListener("pointermove", function (ev) {
      var drag = self.drag;
      if (!drag) return;
      if (!drag.armed && Math.abs(ev.clientX - drag.x) + Math.abs(ev.clientY - drag.y) < DRAG_PX) return;
      drag.armed = true;
      // the pointer may have moved into another day column
      var target = document.elementFromPoint(ev.clientX, ev.clientY);
      var other = target && target.closest ? target.closest(".kc-col") : null;
      var c = other ? +other.dataset.col : ci, colEl = other || col;
      var j = self.slotAt(c, ev.clientY - colEl.getBoundingClientRect().top);
      if (j >= 0) drag.last = j;
      self.highlight(drag.first, drag.last);
    });
    col.addEventListener("pointerup", function () {
      var drag = self.drag;
      if (!drag) return;
      clearTimeout(drag.timer);
      self.drag = null;
      if (!drag.armed) {
        self.hint("To book, drag across the slots you want, or press and hold on a slot.");
        return;
      }
      var slots = self.data.slots;
      var a = slots[Math.min(drag.first, drag.last)], b = slots[Math.max(drag.first, drag.last)];
      self.openBooking(a.start, b.end);
    });
    col.addEventListener("pointercancel", function () {
      if (self.drag) clearTimeout(self.drag.timer);
      self.drag = null;
      self.highlight(-1, -1);
    });
  };

  KherveCal.prototype.hint = function (text) {
    var t = this.toast;
    t.textContent = text;
    t.classList.add("show");
    clearTimeout(this.toastTimer);
    this.toastTimer = setTimeout(function () { t.classList.remove("show"); }, 3500);
  };

  // -- the booking window: the same rules and prices as the app ---------------------------
  KherveCal.prototype.modal = function (inner) {
    var self = this;
    var back = el("div", "kc-modal-back");
    var box = el("div", "kc-modal");
    box.appendChild(inner);
    back.appendChild(box);
    back.addEventListener("click", function (ev) { if (ev.target === back) self.closeModal(); });
    document.body.appendChild(back);
    this.modalEl = back;
  };
  KherveCal.prototype.closeModal = function () {
    if (this.modalEl) { this.modalEl.remove(); this.modalEl = null; }
    this.highlight(-1, -1);
  };

  KherveCal.prototype.openBooking = function (start, end) {
    var self = this, o = this.o;
    var url = o.quoteUrl + "?instrument=" + o.instrument + "&start=" + encodeURIComponent(start) +
      "&end=" + encodeURIComponent(end);
    fetch(url, { credentials: "same-origin" }).then(function (r) { return r.json(); }).then(function (q) {
      var f = el("form");
      f.method = "post";
      f.action = o.bookUrl;
      f.appendChild(el("h2", null, "Book " + o.name));
      var list = el("div", "kc-items");
      q.items.forEach(function (it) {
        var row = el("div", "kc-item" + (it.errors.length ? " bad" : ""));
        var span = it.start.slice(0, 10) === it.end.slice(0, 10)
          ? it.start.replace("T", " ") + "–" + hhmm(it.end)
          : it.start.replace("T", " ") + " → " + it.end.replace("T", " ");
        row.appendChild(el("div", null, (it.label ? it.label + " · " : "") + span));
        row.appendChild(el("b", null, money(q.currency, it.cost)));
        list.appendChild(row);
        it.errors.forEach(function (e) { list.appendChild(el("div", "kc-error", "• " + e)); });
      });
      f.appendChild(list);
      f.appendChild(el("p", "kc-total", "Total " + money(q.currency, q.total)));
      f.appendChild(el("p", q.instant ? "kc-ok" : "kc-warn",
        q.instant ? "Approved at once." : "Needs the lab manager's approval."));
      var purpose = el("textarea");
      purpose.name = "purpose";
      purpose.placeholder = "What you will measure, samples";
      f.appendChild(purpose);
      var first = q.items[0], last = q.items[q.items.length - 1];
      [["csrf", o.csrf], ["instrument_id", o.instrument],
       ["start", first ? first.start : start], ["end", last ? last.end : end]].forEach(function (h) {
        var i = el("input"); i.type = "hidden"; i.name = h[0]; i.value = h[1]; f.appendChild(i);
      });
      var row = el("div", "kc-actions");
      var cancel = el("button", "kc-btn", "Cancel");
      cancel.type = "button";
      cancel.addEventListener("click", function () { self.closeModal(); });
      var ok = el("button", "kc-btn primary", q.instant ? "Book" : "Request approval");
      ok.type = "submit";
      ok.disabled = !q.bookable;
      row.appendChild(cancel); row.appendChild(ok);
      f.appendChild(row);
      self.modal(f);
      purpose.focus();
    });
  };

  KherveCal.prototype.showBooking = function (bk) {
    var self = this, o = this.o, cur = this.data.currency;
    var box = el("div");
    box.appendChild(el("h2", null, o.name));
    box.appendChild(el("p", null, bk.start.replace("T", " ") + " → " + bk.end.replace("T", " ")));
    box.appendChild(el("p", null, bk.who + " · " + bk.status));
    if (bk.purpose) box.appendChild(el("p", "muted", bk.purpose));
    if (bk.cost != null) box.appendChild(el("p", null, "Cost " + money(cur, bk.cost)));
    if (bk.issue) box.appendChild(el("p", "kc-error", bk.issue === "down" ? "The instrument is out of order during this booking." : "A problem is reported during this booking."));
    var row = el("div", "kc-actions");
    if (bk.cancellable) {
      var f = el("form");
      f.method = "post";
      f.action = o.cancelUrl.replace("/0/", "/" + bk.id + "/");
      f.addEventListener("submit", function (ev) { if (!confirm("Cancel this booking?")) ev.preventDefault(); });
      [["csrf", o.csrf], ["back", location.pathname + "?date=" + bk.start.slice(0, 10)]].forEach(function (h) {
        var i = el("input"); i.type = "hidden"; i.name = h[0]; i.value = h[1]; f.appendChild(i);
      });
      var c = el("button", "kc-btn danger", "Cancel booking");
      c.type = "submit";
      f.appendChild(c);
      row.appendChild(f);
    }
    var close = el("button", "kc-btn", "Close");
    close.type = "button";
    close.addEventListener("click", function () { self.closeModal(); });
    row.appendChild(close);
    box.appendChild(row);
    this.modal(box);
  };

  window.KherveCal = KherveCal;
})();
